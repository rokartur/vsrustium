// Builds port/ledger.md rows from the upstream tree and merges them with the rows already in the file,
// so statuses and evidence written by hand survive a rerun. Run from the repo root: bun port/tools/gen-ledger.ts
import { readdirSync, existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { vscodeSrc } from './vscode-src.ts';

type Row = { id: string; area: string; status: string; evidence: string };

const ledgerPath = 'port/ledger.md';
const header = `# Port ledger

One row per unit of upstream (VS Code 1.147.0) that the native app must cover.
Status: \`todo\` (not started), \`stub\` (answers without the real behavior), \`ported\` (behavior written, upstream tests not all passing yet), \`verified\` (upstream tests or the named check pass), \`removed\` (left out by a product decision, see port/notes.md).
Evidence names the narrowest check that can fail on the row. Rows are generated by \`bun port/tools/gen-ledger.ts\`; status and evidence are edited by hand and kept on rerun.

| id | area | status | evidence |
|----|------|--------|----------|
`;

const rows: Row[] = [];
const add = (id: string, area: string) => rows.push({ id, area, status: 'todo', evidence: '' });

for (const id of ['seam/framing', 'seam/rpc', 'seam/handshake', 'seam/init-data', 'seam/bun-runtime', 'seam/node-control', 'seam/vscode-module-bun']) {
	add(id, 'extension host seam');
}

const protocol = readFileSync(join(vscodeSrc, 'src/vs/workbench/api/common/extHost.protocol.ts'), 'utf8');
for (const match of protocol.matchAll(/^export interface (MainThread\w+)Shape/gm)) {
	add(`mainthread/${match[1]}`, 'MainThread* shape (Rust side)');
}

const folders = (dir: string) => readdirSync(join(vscodeSrc, dir)).filter(name => statSync(join(vscodeSrc, dir, name)).isDirectory()).sort();
for (const name of folders('src/vs/base')) {
	add(`base/${name}`, 'src/vs/base');
}
for (const name of folders('src/vs/platform')) {
	add(`platform/${name}`, 'src/vs/platform');
}
for (const name of folders('src/vs/editor')) {
	if (name !== 'contrib') {
		add(`editor/${name}`, 'src/vs/editor');
	}
}
for (const name of folders('src/vs/editor/contrib')) {
	add(`editor/contrib/${name}`, 'src/vs/editor/contrib');
}
for (const name of folders('src/vs/workbench/browser/parts')) {
	if (name !== 'media') {
		add(`workbench/parts/${name}`, 'workbench part');
	}
}
for (const name of folders('src/vs/workbench/services')) {
	add(`workbench/services/${name}`, 'workbench service');
}
for (const name of folders('src/vs/workbench/contrib')) {
	add(`workbench/contrib/${name}`, 'workbench contribution');
}
for (const name of folders('extensions')) {
	if (existsSync(join(vscodeSrc, 'extensions', name, 'package.json'))) {
		add(`extension/${name}`, 'built-in extension');
	}
}
for (const id of ['telemetry/source-search', 'telemetry/network-capture', 'gallery/open-vsx', 'look/screenshot-diff', 'perf/memory-benchmark']) {
	add(id, 'cross-cutting check');
}

const kept = new Map<string, Row>();
if (existsSync(ledgerPath)) {
	for (const line of readFileSync(ledgerPath, 'utf8').split('\n')) {
		const cells = line.split('|').map(cell => cell.trim());
		if (cells.length === 6 && cells[1] && cells[1] !== 'id' && !cells[1].startsWith('-')) {
			kept.set(cells[1], { id: cells[1], area: cells[2], status: cells[3], evidence: cells[4] });
		}
	}
}

const lines = rows.map(row => {
	const old = kept.get(row.id);
	kept.delete(row.id);
	return `| ${row.id} | ${row.area} | ${old?.status ?? row.status} | ${old?.evidence ?? row.evidence} |`;
});
// Rows added by hand (not generated) stay at the end.
for (const row of kept.values()) {
	lines.push(`| ${row.id} | ${row.area} | ${row.status} | ${row.evidence} |`);
}
await Bun.write(ledgerPath, header + lines.join('\n') + '\n');

const counts: Record<string, number> = {};
for (const line of lines) {
	const status = line.split('|')[3].trim();
	counts[status] = (counts[status] ?? 0) + 1;
}
console.log(lines.length, 'rows', counts);
