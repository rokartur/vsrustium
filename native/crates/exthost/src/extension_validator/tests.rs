/// `productVersion` of the upstream test, which is the product date: 2021-05-11T21:54:30.577Z.
const PRODUCT_DATE: Option<i64> = Some(1_620_770_070_577);

#[test]
fn is_valid_version_cases() {
    for (version, desired, expected) in IS_VALID_VERSION {
        assert_eq!(is_valid_version(version, PRODUCT_DATE, desired), *expected, "{version} against {desired}");
    }
}

#[test]
fn is_valid_extension_version_cases() {
    for (version, desired, is_builtin, has_main, expected) in IS_VALID_EXTENSION_VERSION {
        let mut manifest = serde_json::json!({ "name": "test", "publisher": "test", "version": "0.0.0", "engines": { "vscode": desired } });
        if *has_main {
            manifest["main"] = "something".into();
        }
        let result = is_valid_extension_version(version, PRODUCT_DATE, &manifest, *is_builtin);
        assert_eq!(result.is_ok(), *expected, "{version} against {desired}, builtin {is_builtin}, main {has_main}: {result:?}");
    }
}

#[test]
fn checks_browser_only_extensions() {
    let manifest = serde_json::json!({ "name": "test", "publisher": "test", "version": "0.0.0", "engines": { "vscode": "^1.45.0" }, "browser": "something" });
    assert!(is_valid_extension_version("1.44.0", None, &manifest, false).is_err());
}

#[test]
fn parses_and_normalizes() {
    let parsed = parse_version("^1.10.2").unwrap();
    assert_eq!((parsed.has_caret, parsed.major_base, parsed.minor_base, parsed.patch_base), (true, 1, 10, 2));
    assert_eq!(parse_version("0.10"), None);
    assert_eq!(parse_version("0.x.x.x"), None);
    let normalized = normalize_version(parse_version("^1.10.0-20210511").unwrap());
    assert_eq!((normalized.minor_must_equal, normalized.not_before), (false, 1_620_691_200_000));
}

#[test]
fn rejects_an_unspecific_engine() {
    let manifest = serde_json::json!({ "name": "a", "publisher": "p", "version": "1.0.0", "engines": { "vscode": "x.x.x" }, "main": "./out" });
    let error = validate_extension_manifest("1.147.0", None, &manifest, false).unwrap_err();
    assert_eq!(error, "Version specified in `engines.vscode` (x.x.x) is not specific enough. For vscode versions before 1.0.0, please define at a minimum the major and minor desired version. E.g. ^0.10.0, 0.10.x, 0.11.0, etc.");
    let manifest = serde_json::json!({ "name": "a", "publisher": "p", "version": "1.0.0", "engines": { "vscode": "^1.200.0" }, "main": "./out" });
    let error = validate_extension_manifest("1.147.0", None, &manifest, false).unwrap_err();
    assert_eq!(error, "Extension is not compatible with Code 1.147.0. Extension requires: ^1.200.0.");
}
